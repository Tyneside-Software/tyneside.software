def slug(n: int, title: str) -> str:
    s = title.lower()
    for a, b in [
        ("'", ""),
        ("'", ""),
        ("—", "-"),
        ("/", "-"),
        ("(", ""),
        (")", ""),
        (",", ""),
        (":", ""),
        ("?", ""),
        ("!", ""),
        ("α", "a"),
        ("ω", "o"),
        (" ", "-"),
    ]:
        s = s.replace(a, b)
    # keep only safe filename chars
    s = "".join(c if c.isalnum() or c in "-_" else "-" for c in s)
    while "--" in s:
        s = s.replace("--", "-")
    return f"ch-{n:02d}-{s.strip('-')}.md"


