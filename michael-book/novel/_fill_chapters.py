    written = []
    for n, (title, body) in sorted(CHAPTERS.items()):
        body = body.strip() + "\n"
        text = f"# Chapter {n}\n## {title}\n\n{body}"
        path = OUT / slug(n, title)
        path.write_text(text, encoding="utf-8")
        written.append((n, path.name, len(body.split())))
    print(f"Wrote {len(written)} chapters")
    total = sum(w for _, _, w in written)
    print(f"Words in new chapters: {total}")
    for n, name, w in written[:5]:
        print(f"  sample {n}: {name} ({w} w)")
    print("  ...")
    for n, name, w in written[-3:]:
        print(f"  sample {n}: {name} ({w} w)")


